#!/usr/bin/env python3
"""Builds data/seed.js from ../jira-tickets/*.md.

Run after editing tickets:   python3 tools/build_seed.py
The app loads this seed the first time a browser opens it (or after "Reset board").
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TICKETS_DIR = ROOT.parent / "jira-tickets"
OUT = ROOT / "data" / "seed.js"
TYPES = ["Bug", "Story", "Task"]

FIELD_MAP = {
    "type": "type", "priority": "priority", "severity": "severity",
    "component": "component", "labels": "labels", "story points": "storyPoints",
    "affects version": "affectsVersion", "environment": "environment",
    "reporter": "reporter", "epic": "epic", "due date": "dueDate",
}


def parse_ticket(text: str) -> dict | None:
    lines = text.splitlines()
    if not lines:
        return None
    m = re.match(r"#\s+([A-Z]+-\d+)\s+·\s+(.*)", lines[0])
    if not m:
        return None
    key, summary = m.group(1), m.group(2).strip()
    fields: dict = {}
    i = 1
    while i < len(lines) and not lines[i].startswith("|"):
        i += 1
    while i < len(lines) and lines[i].startswith("|"):
        cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
        if len(cells) >= 2:
            label = cells[0].replace("*", "").strip().lower()
            if label in FIELD_MAP:
                fields[FIELD_MAP[label]] = cells[1].strip()
        i += 1

    issue_type = fields.get("type", "Task").split(" ")[0]
    labels = [l.strip().strip("`") for l in fields.pop("labels", "").split(",") if l.strip()]
    if "(Security)" in fields.get("type", "") and "security" not in labels:
        labels.append("security")
    points = fields.pop("storyPoints", "")
    fields.pop("type", None)
    description = "\n".join(lines[i:]).strip()
    description = re.sub(r"^## Description\s*\n", "", description)
    return {
        "key": key,
        "summary": summary,
        "type": issue_type if issue_type in TYPES else "Task",
        "description": description,
        "labels": labels,
        "storyPoints": int(points) if points.isdigit() else None,
        **fields,
    }



def main() -> None:
    files = sorted(TICKETS_DIR.glob("bugs/*.md")) + sorted(TICKETS_DIR.glob("stories/*.md"))
    issues = []
    for path in files:
        parsed = parse_ticket(path.read_text(encoding="utf-8"))
        if parsed:
            issues.append(parsed)
    seed = {
        "version": 1,
        "project": {"key": "OMS", "name": "Order Management Service"},
        "users": [{"name": "Mentor"}, {"name": "Revanth"}],
        "issues": issues,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by tools/build_seed.py - do not edit by hand.\nwindow.ISSUEBOARD_SEED = "
                   + json.dumps(seed, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"Wrote {len(issues)} issues to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
